/// Имя регистра для диагностики неподдерживаемой периферии.
pub fn name(addr: u16) -> &'static str {
    match addr {
        0x3F => "EECR",
        0x40 => "EEDR",
        0x41 => "EEARL",
        0x42 => "EEARH",
        0x43 => "GTCCR",
        0x4C => "SPCR",
        0x4D => "SPSR",
        0x4E => "SPDR",
        0x50 => "ACSR",
        0x53 => "SMCR",
        0x57 => "SPMCSR",
        0x60 => "WDTCSR",
        0x61 => "CLKPR",
        0x64 => "PRR",
        0x66 => "OSCCAL",
        0x78 => "ADCL",
        0x79 => "ADCH",
        0x7A => "ADCSRA",
        0x7B => "ADCSRB",
        0x7C => "ADMUX",
        0x7E => "DIDR0",
        0x7F => "DIDR1",
        0xB6 => "ASSR",
        0xB8 => "TWBR",
        0xB9 => "TWSR",
        0xBA => "TWAR",
        0xBB => "TWDR",
        0xBC => "TWCR",
        0xBD => "TWAMR",
        _ => "reserved",
    }
}
